import { afterAll, beforeAll, expect, it, vi } from "vitest";
const sessao = vi.hoisted(() => ({ id: "" }));
vi.mock("@/biblioteca/prisma", async () => ({ prisma: (await import("../../testes/utilitarios/banco-compartilhamento")).bancoTeste }));
vi.mock("@/servidor/autenticacao", () => ({ obterUsuarioAtual: async () => sessao.id ? { id: sessao.id, nome: "Conta", nomeUsuario: "conta", administradorIa: false } : null }));
vi.mock("@/servidor/ia/configuracoes", () => ({ listarCredenciaisAtivas: async () => [] }));
import { bancoTeste as banco, fecharBancoTeste } from "../../testes/utilitarios/banco-compartilhamento";
import { GET as listar, POST as aderir } from "@/app/api/compartilhamentos/modulos/route";
import { POST as gerar, GET as consultar, DELETE as encerrar } from "@/app/api/modulos/[identificador]/compartilhamento/route";
import { GET as dashboard } from "@/app/api/compartilhamentos/modulos/[moduloId]/route";
import { POST as interpretar } from "@/app/api/compartilhamentos/modulos/[moduloId]/interpretacoes/route";
import { GET as lerSessao, PATCH as editarSessao } from "@/app/api/sessoes/[id]/route";
let dono: string, convidado: string, moduloId: string, sessaoId: string;
const contexto = { params: Promise.resolve({ identificador: "teste" }) };
const requisicao = (corpo?: unknown) => new Request("http://localhost/api/teste", { method: corpo ? "POST" : "GET", ...(corpo ? { body: JSON.stringify(corpo), headers: { "Content-Type": "application/json" } } : {}) });
beforeAll(async () => {
  const contas = await Promise.all(["Dono", "Convidado"].map((nome) => banco.usuario.create({ data: { nome, nomeUsuario: nome, senhaHash: "sintetica" } })));
  [dono, convidado] = contas.map((conta) => conta.id);
  moduloId = (await banco.moduloAprendizagem.create({ data: { usuarioId: dono, identificador: "teste", titulo: "Módulo teste", descricao: "PRIVADO" } })).id;
  sessaoId = (await banco.sessaoEstudo.create({ data: { usuarioId: dono, moduloId, descricao: "SESSAO_PRIVADA", iniciadaEm: new Date("2026-10-01T10:00Z"), encerradaEm: new Date("2026-10-01T10:30Z"), duracaoMinutos: 30, modoRegistro: "MANUAL", situacao: "CONCLUIDA" } })).id;
});
afterAll(fecharBancoTeste);
it("rotas autenticam, autorizam, validam período e negam dashboard após encerramento", async () => {
  expect((await listar()).status).toBe(401);
  sessao.id = dono;
  const resposta = await gerar(requisicao(), contexto);
  expect(resposta.status).toBe(200);
  const { compartilhamento } = await resposta.json();
  sessao.id = convidado;
  expect((await consultar(requisicao(), contexto)).status).toBe(404);
  expect((await aderir(requisicao({ codigo: compartilhamento.codigo }))).status).toBe(200);
  const ctx = { params: Promise.resolve({ moduloId }) };
  const leitura = await dashboard(requisicao(), ctx);
  expect(leitura.status).toBe(200);
  expect(leitura.headers.get("cache-control")).toBe("no-store");
  expect(JSON.stringify(await leitura.json())).not.toContain("PRIVADO");
  const ctxSessao = { params: Promise.resolve({ id: sessaoId }) };
  expect((await lerSessao(requisicao(), ctxSessao)).status).toBe(404);
  const tentativaEdicao = requisicao({ descricao: "ALTERACAO_INDEVIDA", iniciadaEm: "2026-10-01T10:00:00Z", encerradaEm: "2026-10-01T10:30:00Z", dificuldadePercebida: 2, compreensaoPercebida: 4, metodos: ["FEYNMAN"], formatos: ["TEXTO"], materialIds: [] });
  expect((await editarSessao(tentativaEdicao, ctxSessao)).status).toBe(404);
  expect((await banco.sessaoEstudo.findUniqueOrThrow({ where: { id: sessaoId } })).descricao).toBe("SESSAO_PRIVADA");
  expect((await dashboard(new Request("http://localhost/api?inicio=invalido"), ctx)).status).toBe(400);
  expect((await interpretar(requisicao(), { params: Promise.resolve({ moduloId: "outro" }) })).status).toBe(403);
  expect((await encerrar(requisicao(), contexto)).status).toBe(404);
  sessao.id = dono;
  expect((await encerrar(requisicao(), contexto)).status).toBe(200);
  sessao.id = convidado;
  expect((await dashboard(requisicao(), ctx)).status).toBe(403);
  expect((await interpretar(requisicao(), ctx)).status).toBe(403);
  expect((await listar()).status).toBe(200);
  expect((await (await listar()).json()).modulos).toEqual([]);
});
